create function public.gi_sync_legacy_defense() returns trigger language plpgsql security definer set search_path='' as $$
declare ids integer[]; leader integer;
begin
 if new.gi_defense_id is null and new.kind='counter' and new.visibility='guild' and new.guild_id is not null and new.moderation_status='approved' and coalesce(new.payload->'offense'->>'gameMode','siege')='siege' then
  ids=public.gi_payload_ids(new.payload,'defense');
  if public.gi_valid_ids(ids) and public.gi_payload_key(new.payload) is not null and public.guild_payload_is_portable(new.payload,'counter') then
   leader=coalesce((new.payload->'siege'->>'defenseLeaderIndex')::integer,0);
   insert into public.siege_defense_catalog(guild_id,monster_ids,leader_index,source_kind,source_name,observed_at,created_by)
   values(new.guild_id,ids,leader,'guild','Acervo existente da guilda',new.updated_at,new.owner_id) on conflict do nothing;
  end if;
 end if;return new;
end $$;
create trigger gi_legacy_counter_catalog after insert or update of payload,moderation_status,visibility,guild_id on public.guild_teams for each row execute function public.gi_sync_legacy_defense();
-- Bring real, compatible guild defenses into the catalog. No fabricated trends,
-- and no conversion of legacy opinions/outcome labels into battle events.
do $$ declare row record; ids integer[]; leader integer;begin
 if to_regprocedure('public.guild_payload_is_portable(jsonb,text)') is not null then
 for row in select * from public.guild_teams where kind='counter' and visibility='guild' and guild_id is not null and moderation_status='approved' loop
  ids=public.gi_payload_ids(row.payload,'defense');
  if public.gi_valid_ids(ids) and public.gi_payload_key(row.payload) is not null and public.guild_payload_is_portable(row.payload,'counter') and coalesce(row.payload->'offense'->>'gameMode','siege')='siege' then
   leader=coalesce((row.payload->'siege'->>'defenseLeaderIndex')::integer,0);
   insert into public.siege_defense_catalog(guild_id,monster_ids,leader_index,source_kind,source_name,observed_at,created_by)
   values(row.guild_id,ids,leader,'guild','Acervo existente da guilda',row.updated_at,row.owner_id) on conflict do nothing;
  end if;
 end loop;end if;
end $$;
