create function public.gi_trio_key(ids integer[],leader integer) returns text language plpgsql immutable set search_path='' as $$
declare rest text;
begin
 if ids is null or cardinality(ids)<>3 or array_ndims(ids)<>1 or array_lower(ids,1)<>1 or leader is null or leader not between 0 and 2 or exists(select 1 from unnest(ids) v where v is null or v<10000) or (select count(distinct v) from unnest(ids) v)<>3 then raise exception 'Selecione três monstros distintos e um líder válido.';end if;
 select string_agg(v::text,':' order by v) into rest from unnest(ids) with ordinality u(v,i) where i<>leader+1;
 return ids[leader+1]::text||':'||rest;
end $$;
create function public.gi_valid_ids(ids integer[]) returns boolean language sql stable security definer set search_path='' as $$
 select cardinality(ids)=3 and (select count(*)=3 from unnest(ids) v join public.guild_intelligence_monsters m on m.master_id=v);
$$;
create function public.gi_payload_ids(doc jsonb,field text) returns integer[] language plpgsql immutable set search_path='' as $$
declare ids integer[];begin
 if field='defense' then select array_agg((v->>'masterId')::integer order by i) into ids from jsonb_array_elements(doc->'enemyDefense') with ordinality u(v,i);
 else select array_agg((v->>'masterId')::integer order by i) into ids from jsonb_array_elements(doc->'offense'->'configs') with ordinality u(v,i);end if;return ids;
exception when others then return null;end $$;
create function public.gi_payload_key(doc jsonb) returns text language plpgsql immutable set search_path='' as $$
begin return public.gi_trio_key(public.gi_payload_ids(doc,'defense'),coalesce((doc->'siege'->>'defenseLeaderIndex')::integer,0));exception when others then return null;end $$;
