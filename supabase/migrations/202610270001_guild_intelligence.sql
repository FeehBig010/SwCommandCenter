create function public.gi_save_defenses(target_guild uuid,entries jsonb,target_id uuid default null) returns jsonb language plpgsql security definer set search_path='' as $$
declare item jsonb; ids integer[]; leader integer; existing uuid; result_ids uuid[]='{}'; inserted integer=0; rank_value text; pop jsonb; source text; updated timestamptz;
begin
 perform public.gi_require_member(target_guild);if not public.is_guild_leader(target_guild) then raise exception 'Somente a liderança pode administrar o catálogo.' using errcode='42501';end if;
 if jsonb_typeof(entries) is distinct from 'array' or jsonb_array_length(entries) not between 1 and 200 or octet_length(entries::text)>500000 or target_id is not null and jsonb_array_length(entries)<>1 then raise exception 'Importe entre 1 e 200 defesas válidas.';end if;
 for item in select value from jsonb_array_elements(entries) loop
  if jsonb_typeof(item)<>'object' or item-array['monster_ids','leader_index','category','tier','source_kind','origin_kind','source_name','source_url','observed_at','authorization','popularity']<>'{}'::jsonb then raise exception 'Campos de defesa inválidos.';end if;
  select array_agg(v::integer order by i) into ids from jsonb_array_elements_text(item->'monster_ids') with ordinality u(v,i);
  leader=coalesce((item->>'leader_index')::integer,0);perform public.gi_trio_key(ids,leader);if not public.gi_valid_ids(ids) then raise exception 'IDs desconhecidos no catálogo de monstros.';end if;
  if item->>'category' is not null and (item->>'category')::integer not in (4,5) or item->>'tier' is not null and item->>'tier' not in ('G1','G2','G3') then raise exception 'Categoria ou faixa inválida.';end if;
  source=item->>'source_kind';if source is null or source not in ('guild','authorized_import') or length(btrim(coalesce(item->>'source_name',''))) not between 1 and 120 then raise exception 'Informe a origem dos dados.';end if;
  if coalesce(item->>'origin_kind',case when source='guild' then 'guild' else 'external' end) not in ('guild','external') then raise exception 'Origem inválida.';end if;
 if source='authorized_import' and length(btrim(coalesce(item->>'authorization',''))) not between 1 and 500 then raise exception 'Informe a autorização para importar esta origem.';end if;
  updated=(item->>'observed_at')::timestamptz;if updated is null or not isfinite(updated) or updated<'1970-01-01' or updated>now()+interval '1 minute' then raise exception 'Informe a data real da atualização.';end if;
  pop=nullif(item->'popularity','null'::jsonb);
  if target_id is not null then
   select id into existing from public.siege_defense_catalog where id=target_id and guild_id=target_guild and composition_key=public.gi_trio_key(ids,leader) for update;
   if existing is null then raise exception 'A composição existente não pode ser substituída. Cadastre outra defesa.';end if;
   update public.siege_defense_catalog set category=(item->>'category')::smallint,tier=item->>'tier',source_kind=source,origin_kind=coalesce(item->>'origin_kind',case when source='guild' then 'guild' else 'external' end),source_name=btrim(item->>'source_name'),source_url=nullif(item->>'source_url',''),rights_statement=nullif(item->>'authorization',''),popularity=pop,observed_at=updated,updated_at=clock_timestamp() where id=existing;
  else
   existing=null;insert into public.siege_defense_catalog(guild_id,monster_ids,leader_index,category,tier,source_kind,origin_kind,source_name,source_url,rights_statement,popularity,observed_at,created_by)
   values(target_guild,ids,leader,(item->>'category')::smallint,item->>'tier',source,coalesce(item->>'origin_kind',case when source='guild' then 'guild' else 'external' end),btrim(item->>'source_name'),nullif(item->>'source_url',''),nullif(item->>'authorization',''),pop,updated,auth.uid()) on conflict(guild_id,composition_key) do nothing returning id into existing;
   if existing is null then select id into existing from public.siege_defense_catalog where guild_id=target_guild and composition_key=public.gi_trio_key(ids,leader);else inserted=inserted+1;end if;
  end if;
  result_ids=array_append(result_ids,existing);
 end loop;
 return jsonb_build_object('ids',result_ids,'inserted',inserted,'existing',jsonb_array_length(entries)-inserted);
end $$;
create function public.gi_counter_visible(t public.guild_teams) returns boolean language plpgsql stable security definer set search_path='' as $$
begin return t.kind='counter' and t.visibility='guild' and public.is_guild_member(t.guild_id) and public.can_access_siege_counter(t.id) and public.guild_payload_is_portable(t.payload,t.kind) and coalesce(t.payload->'offense'->>'gameMode','siege')='siege' and public.gi_payload_key(t.payload) is not null;end $$;
create function public.gi_save_counter(target_guild uuid,defense_id uuid,document jsonb,request_id uuid,preset_name text default null,preset_ref text default null,target_id uuid default null,expected_updated timestamptz default null) returns uuid language plpgsql security definer set search_path='' as $$
declare defense public.siege_defense_catalog; row public.guild_teams; ids integer[]; leader integer; result uuid; actor uuid=auth.uid();
begin
 perform public.gi_require_member(target_guild);
 if request_id is null then raise exception 'Identificador da solicitação ausente.';end if;
 select * into defense from public.siege_defense_catalog where id=defense_id and guild_id=target_guild;
 if defense.id is null then raise exception 'Defesa não encontrada na guilda ativa.';end if;
 ids=public.gi_payload_ids(document,'offense');leader=coalesce((document->'offense'->>'leaderIndex')::integer,0);perform public.gi_trio_key(ids,leader);
 if not public.gi_valid_ids(ids) or not public.guild_payload_is_portable(document,'counter') or octet_length(document::text)>100000 or document->'version' is distinct from '1'::jsonb or document->'offense'->>'gameMode' is distinct from 'siege' or document->'offense'->>'mode' is distinct from 'attack' or public.gi_payload_key(document) is distinct from defense.composition_key then raise exception 'Composição ou defesa inválida. Nenhum inventário privado pode ser compartilhado.';end if;
 if jsonb_typeof(document->'name') is distinct from 'string' or jsonb_typeof(document->'notes') is distinct from 'string' or jsonb_typeof(document->'offense'->'name') is distinct from 'string' or exists(select 1 from jsonb_array_elements(document->'offense'->'configs') c where jsonb_typeof(c->'label') is distinct from 'string' or length(btrim(c->>'label')) not between 1 and 80) then raise exception 'Nome, estratégia ou rótulos inválidos.';end if;
 if length(coalesce(document->>'notes',''))>1000 or length(btrim(coalesce(document->>'name',''))) not between 1 and 100 or coalesce(document->>'outcome','unrecorded')<>'unrecorded' then raise exception 'Salve a estratégia sem resultado; registre combates separadamente.';end if;
 if preset_name is not null and length(btrim(preset_name)) not between 1 and 100 or preset_ref is not null and preset_ref!~'^[a-f0-9]{64}$' or (preset_name is null)<>(preset_ref is null) then raise exception 'Referência de preset inválida.';end if;
 if target_id is null then
  select id into result from public.guild_teams where owner_id=actor and gi_request_id=request_id and guild_id=target_guild;if result is not null then return result;end if;
  insert into public.guild_teams(owner_id,guild_id,kind,visibility,name,payload,moderation_status,gi_defense_id,gi_offense_ids,gi_leader_index,gi_preset_name,gi_preset_ref,gi_request_id)
  values(actor,target_guild,'counter','guild',btrim(document->>'name'),document,'approved',defense_id,ids,leader,preset_name,preset_ref,request_id) returning id into result;
 else
  select * into row from public.guild_teams where id=target_id and guild_id=target_guild for update;
  if row.id is null or not public.gi_counter_visible(row) or (row.owner_id<>actor and not public.is_guild_leader(target_guild)) then raise exception 'Sem permissão para editar este counter.' using errcode='42501';end if;
  if expected_updated is null or row.updated_at<>expected_updated then raise exception 'O counter mudou. Atualize antes de salvar.' using errcode='40001';end if;
  update public.guild_teams set name=btrim(document->>'name'),payload=document,gi_defense_id=defense_id,gi_offense_ids=ids,gi_leader_index=leader,gi_preset_name=preset_name,gi_preset_ref=preset_ref,moderation_status='approved' where id=row.id;result=row.id;
 end if;
 return result;
exception when unique_violation then raise exception 'Você já cadastrou esta composição com este preset para essa defesa. Edite o counter existente.' using errcode='23505';
end $$;
create function public.gi_remove_counter(target_guild uuid,target_id uuid,expected_updated timestamptz) returns void language plpgsql security definer set search_path='' as $$
declare row public.guild_teams;begin perform public.gi_require_member(target_guild);select * into row from public.guild_teams where id=target_id and guild_id=target_guild for update;
 if row.id is null or not public.gi_counter_visible(row) or (row.owner_id<>auth.uid() and not public.is_guild_leader(target_guild)) then raise exception 'Sem permissão para excluir este counter.' using errcode='42501';end if;
 if expected_updated is null or row.updated_at<>expected_updated then raise exception 'O counter mudou. Atualize a biblioteca.' using errcode='40001';end if;delete from public.guild_teams where id=row.id;
end $$;
create function public.gi_save_battle(target_guild uuid,target_counter uuid,result text,battle_date timestamptz,observation text,request_id uuid,target_id uuid default null,expected_updated timestamptz default null) returns uuid language plpgsql security definer set search_path='' as $$
declare counter public.guild_teams; old public.guild_counter_battles; saved uuid;
begin
 perform public.gi_require_member(target_guild);select * into counter from public.guild_teams where id=target_counter and guild_id=target_guild for share;
 if counter.id is null or not public.gi_counter_visible(counter) then raise exception 'Counter indisponível nesta guilda.' using errcode='42501';end if;
 if result is null or result not in ('win','loss') or battle_date is null or not isfinite(battle_date) or battle_date>now()+interval '1 minute' or battle_date<'2000-01-01' or length(coalesce(observation,''))>1000 or request_id is null then raise exception 'Resultado, data ou observação inválidos.';end if;
 if target_id is null then
  insert into public.guild_counter_battles(guild_id,counter_id,user_id,outcome,fought_at,notes,request_id) values(target_guild,target_counter,auth.uid(),result,battle_date,coalesce(observation,''),request_id) on conflict on constraint guild_counter_battles_user_id_request_id_key do nothing returning id into saved;
  if saved is null then select id into saved from public.guild_counter_battles b where b.user_id=auth.uid() and b.request_id=gi_save_battle.request_id and b.counter_id=target_counter and b.guild_id=target_guild;if saved is null then raise exception 'Solicitação já utilizada para outro combate.';end if;end if;
 else
  select * into old from public.guild_counter_battles where id=target_id and counter_id=target_counter and guild_id=target_guild for update;
  if old.id is null or old.user_id<>auth.uid() then raise exception 'Somente o autor pode editar o resultado.' using errcode='42501';end if;
  if expected_updated is null or old.updated_at<>expected_updated then raise exception 'O combate mudou. Atualize o histórico.' using errcode='40001';end if;
  update public.guild_counter_battles set outcome=result,fought_at=battle_date,notes=coalesce(observation,''),updated_at=clock_timestamp() where id=old.id;saved=old.id;
 end if;return saved;
end $$;
create function public.gi_remove_battle(target_guild uuid,target_id uuid,expected_updated timestamptz) returns void language plpgsql security definer set search_path='' as $$
declare row public.guild_counter_battles;begin perform public.gi_require_member(target_guild);select * into row from public.guild_counter_battles where id=target_id and guild_id=target_guild for update;
 if row.id is null or (row.user_id<>auth.uid() and not public.is_guild_leader(target_guild)) then raise exception 'Sem permissão para remover este combate.' using errcode='42501';end if;
 if expected_updated is null or row.updated_at<>expected_updated then raise exception 'O combate mudou. Atualize o histórico.' using errcode='40001';end if;delete from public.guild_counter_battles where id=row.id;
end $$;
create function public.gi_remove_defense(target_guild uuid,target_id uuid) returns void language plpgsql security definer set search_path='' as $$
declare row public.siege_defense_catalog;begin perform public.gi_require_member(target_guild);if not public.is_guild_leader(target_guild) then raise exception 'Somente a liderança pode excluir defesas.' using errcode='42501';end if;
 select * into row from public.siege_defense_catalog where id=target_id and guild_id=target_guild for update;if row.id is null then raise exception 'Defesa não encontrada.';end if;
 if exists(select 1 from public.guild_teams t where t.guild_id=target_guild and t.kind='counter' and (t.gi_defense_id=target_id or public.gi_payload_key(t.payload)=row.composition_key)) then raise exception 'Esta defesa possui counters. Preserve o histórico ou remova os counters primeiro.';end if;
 delete from public.siege_defense_catalog where id=row.id;
end $$;
create function public.gi_guard_counter() returns trigger language plpgsql security definer set search_path='' as $$
declare d public.siege_defense_catalog;
begin
 if tg_op='UPDATE' and exists(select 1 from public.guild_counter_battles where counter_id=old.id) and (public.gi_payload_ids(old.payload,'offense') is distinct from public.gi_payload_ids(new.payload,'offense') or public.gi_payload_key(old.payload) is distinct from public.gi_payload_key(new.payload) or old.payload->'offense'->'leaderIndex' is distinct from new.payload->'offense'->'leaderIndex' or old.gi_preset_ref is distinct from new.gi_preset_ref) then raise exception 'A composição possui combates. Cadastre outro counter para preservar o histórico.';end if;
 if new.gi_defense_id is not null then
  select * into d from public.siege_defense_catalog where id=new.gi_defense_id and guild_id=new.guild_id;
  if d.id is null or not public.gi_valid_ids(new.gi_offense_ids) or new.gi_offense_ids is distinct from public.gi_payload_ids(new.payload,'offense') or new.gi_leader_index is distinct from coalesce((new.payload->'offense'->>'leaderIndex')::integer,0) or d.composition_key is distinct from public.gi_payload_key(new.payload) or not public.guild_payload_is_portable(new.payload,'counter') then raise exception 'Referências do counter inconsistentes.';end if;
 end if;return new;
end $$;
create trigger gi_counter_integrity before insert or update on public.guild_teams for each row execute function public.gi_guard_counter();
create function public.gi_visible_counters(target_guild uuid) returns setof public.guild_teams language sql stable security definer set search_path='' as $$
 select t.* from public.guild_teams t where t.guild_id=target_guild and public.gi_counter_visible(t);
$$;
create function public.gi_catalog(target_guild uuid,search text default '',category_filter integer default null,tier_filter text default null,ordering text default 'recent',page_offset integer default 0) returns jsonb language plpgsql stable security definer set search_path='' as $$
declare result jsonb;
begin
 perform public.gi_require_member(target_guild);if search is null or length(search)>80 or ordering is null or ordering not in ('recent','name','uncovered','covered','popular') or page_offset is null or page_offset<0 or page_offset>100000 then raise exception 'Filtro inválido.';end if;
 with counters as materialized(select * from public.gi_visible_counters(target_guild)),
 filtered as(select d.*,(select count(*) from counters c where c.gi_defense_id=d.id or c.gi_defense_id is null and public.gi_payload_key(c.payload)=d.composition_key) as counter_count,
 (select string_agg(m.name,' · ' order by i) from unnest(d.monster_ids) with ordinality u(id,i) join public.guild_intelligence_monsters m on m.master_id=u.id) as names
 from public.siege_defense_catalog d where d.guild_id=target_guild and (category_filter is null or d.category=category_filter) and (tier_filter is null or d.tier=tier_filter)),
 matching as(select * from filtered where not exists(select 1 from regexp_split_to_table(lower(btrim(search)),'\s+') token where token<>'' and strpos(lower(names),token)=0)),
 page as(select * from matching order by case when ordering='name' then names end asc,case when ordering='uncovered' then counter_count end asc,case when ordering='covered' then counter_count end desc,case when ordering='popular' then (popularity->>'count')::numeric end desc nulls last,updated_at desc,id limit 50 offset page_offset)
 select jsonb_build_object('rows',coalesce((select jsonb_agg(to_jsonb(p)-'rights_statement') from page p),'[]'::jsonb),'total',(select count(*) from matching)) into result;return result;
end $$;
create function public.gi_counters(target_guild uuid,defense_id uuid,page_offset integer default 0,search text default '',status_filter text default 'all',ordering text default 'recent') returns jsonb language plpgsql stable security definer set search_path='' as $$
declare defense public.siege_defense_catalog; result jsonb;
begin
 perform public.gi_require_member(target_guild);if search is null or length(search)>80 or status_filter is null or status_filter not in ('all','untested','tested','sample') or ordering is null or ordering not in ('recent','battles','winrate') or page_offset is null or page_offset<0 or page_offset>100000 then raise exception 'Página ou filtro inválido.';end if;select * into defense from public.siege_defense_catalog where id=defense_id and guild_id=target_guild;if defense.id is null then raise exception 'Defesa não encontrada.';end if;
 with counters as materialized(select c.* from public.gi_visible_counters(target_guild) c where c.gi_defense_id=defense_id or c.gi_defense_id is null and public.gi_payload_key(c.payload)=defense.composition_key),
 stats as(select c.id,c.owner_id,c.payload,c.created_at,c.updated_at,c.gi_preset_name as preset_name,c.gi_preset_ref as preset_ref,c.gi_defense_id is null as legacy,
 coalesce(nullif(p.display_name,''),'Membro da guilda') as author_label,s.wins,s.losses,s.total,case when s.total>0 then round(s.wins::numeric*100/s.total,1) end as win_rate
 from counters c left join public.profiles p on p.id=c.owner_id cross join lateral(select count(*) filter(where b.outcome='win') as wins,count(*) filter(where b.outcome='loss') as losses,count(*) as total from public.guild_counter_battles b where b.counter_id=c.id and b.guild_id=target_guild) s),
 matching as(select * from stats where (search='' or strpos(lower(author_label||' '||coalesce(payload->>'notes','')||' '||(select string_agg(v->>'label',' ') from jsonb_array_elements(payload->'offense'->'configs') v)),lower(search))>0) and (status_filter='all' or status_filter='untested' and total=0 or status_filter='tested' and total>0 or status_filter='sample' and total between 1 and 4)),
 page as(select * from matching order by case when ordering='winrate' then win_rate end desc nulls last,case when ordering='battles' then total end desc,created_at desc,id limit 50 offset page_offset)
 select jsonb_build_object('rows',coalesce((select jsonb_agg(to_jsonb(p)) from page p),'[]'::jsonb),'total',(select count(*) from matching)) into result;return result;
end $$;
create function public.gi_overview(target_guild uuid) returns jsonb language plpgsql stable security definer set search_path='' as $$
declare result jsonb;
begin
 perform public.gi_require_member(target_guild);
 with counters as materialized(select * from public.gi_visible_counters(target_guild)),
 defenses as(select d.id,exists(select 1 from counters c where c.gi_defense_id=d.id or c.gi_defense_id is null and public.gi_payload_key(c.payload)=d.composition_key) as covered from public.siege_defense_catalog d where d.guild_id=target_guild),
 outcomes as(select count(*) filter(where b.outcome='win') as wins,count(*) filter(where b.outcome='loss') as losses,count(*) as total from public.guild_counter_battles b join counters c on c.id=b.counter_id where b.guild_id=target_guild),
 contributors as(select c.owner_id,coalesce(nullif(p.display_name,''),'Membro da guilda') as name,count(*) as counters from counters c left join public.profiles p on p.id=c.owner_id group by c.owner_id,p.display_name order by count(*) desc,c.owner_id limit 10)
 select jsonb_build_object('counter_count',(select count(*) from counters),'defense_count',(select count(*) from defenses),'covered_count',(select count(*) from defenses where covered),'uncovered_count',(select count(*) from defenses where not covered),'battles',o.total,'wins',o.wins,'losses',o.losses,'win_rate',case when o.total>0 then round(o.wins::numeric*100/o.total,1) end,'contributors',coalesce((select jsonb_agg(to_jsonb(c)) from contributors c),'[]'::jsonb)) into result from outcomes o;return result;
end $$;
create function public.gi_battles(target_guild uuid,target_counter uuid,page_offset integer default 0) returns jsonb language plpgsql stable security definer set search_path='' as $$
declare counter public.guild_teams; result jsonb;
begin
 perform public.gi_require_member(target_guild);select * into counter from public.guild_teams where id=target_counter and guild_id=target_guild;if counter.id is null or not public.gi_counter_visible(counter) then raise exception 'Counter indisponível.' using errcode='42501';end if;
 if page_offset<0 or page_offset>100000 then raise exception 'Página inválida.';end if;
 with page as(select b.id,b.user_id,b.counter_id,b.outcome,b.fought_at,b.notes,b.created_at,b.updated_at,coalesce(nullif(p.display_name,''),'Membro da guilda') as author_label from public.guild_counter_battles b left join public.profiles p on p.id=b.user_id where b.guild_id=target_guild and b.counter_id=target_counter order by b.fought_at desc,b.id limit 50 offset page_offset)
 select jsonb_build_object('rows',coalesce((select jsonb_agg(to_jsonb(p)) from page p),'[]'::jsonb),'total',(select count(*) from public.guild_counter_battles where guild_id=target_guild and counter_id=target_counter)) into result;return result;
end $$;
